    val title: String,
    val url: String,
    val uploader: String,
    val duration: String,
    val thumbnailUrl: String?
)

object MediaHelper {

    private const val USER_AGENT = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/121.0.0.0 Safari/537.36"

    private var isInitialized = false
    private var isNewPipeInitialized = false

    private fun initNewPipe() {
        if (!isNewPipeInitialized) {
            try {
                NewPipe.init(SimpleDownloader(), Localization.DEFAULT, ContentCountry("US"))
                isNewPipeInitialized = true
            } catch (e: Throwable) {
                Log.e("MediaHelper", "NewPipe init failed", e)
            }
        }
    }

    fun getVideoId(url: String): String? {
        val regex = Regex("(?:youtube(?:-nocookie)?\\.com/(?:[^/\\n\\s]+/.+/|(?:v|e(?:mbed)?)/|.*[?&]v=)|youtu\\.be/)([a-zA-Z0-9_-]{11})")
        return regex.find(url)?.groupValues?.get(1)
    }

    private fun fetchVerifiedSubtitles(cleanUrl: String, targetLang: String = "cs"): List<SubtitleTrack> {
        val tracks = mutableListOf<SubtitleTrack>()
        val videoId = getVideoId(cleanUrl)

        // 1. Try NewPipeExtractor subtitles
        try {
            initNewPipe()
            val service = ServiceList.YouTube
            val extractor = service.getStreamExtractor(cleanUrl) as StreamExtractor
            extractor.fetchPage()

            extractor.subtitlesDefault?.forEach { sub ->
                var contentUrl = sub.content
                if (!contentUrl.isNullOrEmpty()) {
                    if (contentUrl.contains("timedtext") && !contentUrl.contains("fmt=vtt")) {
                        contentUrl = if (contentUrl.contains("fmt=")) {
                            contentUrl.replace(Regex("fmt=[^&]+"), "fmt=vtt")
                        } else {
                            "$contentUrl&fmt=vtt"
                        }
                    }
                    val langTag = sub.languageTag ?: "unk"
                    val langName = sub.displayLanguageName ?: langTag

                    tracks.add(
                        SubtitleTrack(
                            language = langTag,
                            name = langName,
                            url = contentUrl,
                            mimeType = "text/vtt",
                            isAutoGenerated = false
                        )
                    )

                    // Add substituted AI track for foreign subtitles
                    if (!langTag.startsWith(targetLang, ignoreCase = true) && contentUrl.contains("timedtext")) {
                        var aiSubUrl = contentUrl
                        aiSubUrl = if (aiSubUrl.contains("tlang=")) aiSubUrl.replace(Regex("tlang=[^&]+"), "tlang=$targetLang") else "$aiSubUrl&tlang=$targetLang"
                        aiSubUrl = if (aiSubUrl.contains("fmt=")) aiSubUrl.replace(Regex("fmt=[^&]+"), "fmt=vtt") else "$aiSubUrl&fmt=vtt"

                        val translatedLangName = if (targetLang == "cs") "Čeština" else "English"
                        tracks.add(
                            SubtitleTrack(
                                language = targetLang,
                                name = "🤖 $langName -> $translatedLangName (AI)",
                                url = aiSubUrl,
                                mimeType = "text/vtt",
                                isAutoGenerated = true
                            )
                        )
                    }
                }
            }
        } catch (e: Throwable) {
            Log.w("MediaHelper", "NewPipe subtitle extraction error", e)
        }

        // 2. Verified AI Subtitles candidate URLs if videoId exists
        if (!videoId.isNullOrEmpty()) {
            val candidateUrls = if (targetLang == "en") {
                listOf(
                    "https://www.youtube.com/api/timedtext?v=$videoId&lang=en&fmt=vtt" to "English",
                    "https://www.youtube.com/api/timedtext?v=$videoId&kind=asr&lang=en&fmt=vtt" to "🤖 English (Auto-generated)",
                    "https://www.youtube.com/api/timedtext?v=$videoId&kind=asr&lang=es&tlang=en&fmt=vtt" to "🤖 English (AI Translated from Spanish)",
                    "https://www.youtube.com/api/timedtext?v=$videoId&kind=asr&lang=fr&tlang=en&fmt=vtt" to "🤖 English (AI Translated from French)",
                    "https://www.youtube.com/api/timedtext?v=$videoId&kind=asr&lang=de&tlang=en&fmt=vtt" to "🤖 English (AI Translated from German)"
                )
            } else {
                listOf(
                    "https://www.youtube.com/api/timedtext?v=$videoId&lang=cs&fmt=vtt" to "Čeština",
                    "https://www.youtube.com/api/timedtext?v=$videoId&kind=asr&lang=en&tlang=cs&fmt=vtt" to "🤖 Čeština (AI automatický překlad)",
                    "https://www.youtube.com/api/timedtext?v=$videoId&kind=asr&lang=fr&tlang=cs&fmt=vtt" to "🤖 Čeština (AI automatický překlad)",
                    "https://www.youtube.com/api/timedtext?v=$videoId&kind=asr&lang=de&tlang=cs&fmt=vtt" to "🤖 Čeština (AI automatický překlad)",
                    "https://www.youtube.com/api/timedtext?v=$videoId&kind=asr&lang=es&tlang=cs&fmt=vtt" to "🤖 Čeština (AI automatický překlad)",
                    "https://www.youtube.com/api/timedtext?v=$videoId&kind=asr&lang=en&tlang=en&fmt=vtt" to "🤖 English (AI Auto-translated)",
                    "https://www.youtube.com/api/timedtext?v=$videoId&kind=asr&lang=en&tlang=de&fmt=vtt" to "🤖 Deutsch (AI Automatisch)"
                )
            }

            for ((url, label) in candidateUrls) {
                if (tracks.any { it.url == url }) continue
                try {
                    val conn = (URL(url).openConnection() as HttpURLConnection).apply {
                        requestMethod = "GET"
                        setRequestProperty("User-Agent", USER_AGENT)
                        connectTimeout = 3000
                        readTimeout = 3000
                    }
                    if (conn.responseCode == 200) {
                        val content = conn.inputStream.bufferedReader().use { it.readText() }
                        if (content.contains("-->")) {
                            val isAi = label.contains("AI") || label.contains("Auto")
                            val isTarget = label.contains(if (targetLang == "cs") "Češt" else "English")
                            tracks.add(
                                if (isAi) 0 else tracks.size,
                                SubtitleTrack(
                                    language = if (isTarget) targetLang else "en",
                                    name = label,
                                    url = url,
                                    mimeType = "text/vtt",
                                    isAutoGenerated = isAi
                                )
                            )
                            if (isTarget) break
                        }
                    }
                } catch (e: Throwable) {
                    Log.w("MediaHelper", "Subtitle check error for $url", e)
                }
            }
        }

        return tracks
    }

    @Suppress("DEPRECATION")
    suspend fun extractMedia(
        context: Context,
        url: String,
        preferredResolution: String = "auto",
        targetLang: String = "cs"
    ): Result<ExtractedMedia> = withContext(Dispatchers.IO) {
        val cleanUrl = url.trim()

        val isAudio = preferredResolution.startsWith("audio")

        val formatSelector = when (preferredResolution) {
            "1080" -> "bestvideo[height<=1080]+bestaudio/best[height<=1080]/18/22/b/best"
            "720" -> "bestvideo[height<=720]+bestaudio/best[height<=720]/18/22/b/best"
            "480" -> "bestvideo[height<=480]+bestaudio/best[height<=480]/18/22/b/best"
            "360" -> "bestvideo[height<=360][vcodec!=none][acodec!=none]/best[height<=360]/18/22/b/best"
            "audio_320", "audio_128", "audio" -> "bestaudio[ext=m4a]/bestaudio/best"
            else -> "best[vcodec!=none][acodec!=none]/18/22/b/best"
        }

        // Extract subtitles list and verify valid WebVTT subtitle cues
        val subtitlesList = fetchVerifiedSubtitles(cleanUrl, targetLang)

        // 1. Try YoutubeDL
        try {
            if (!isInitialized) {
                try {
                    YoutubeDL.getInstance().init(context.applicationContext)
                    FFmpeg.getInstance().init(context.applicationContext)
                    isInitialized = true
                } catch (e: Throwable) {
                    Log.e("MediaHelper", "YoutubeDL init error", e)
                }
            }

            if (isInitialized) {
                val request = YoutubeDLRequest(cleanUrl).apply {
                    addOption("-f", formatSelector)
                    addOption("--no-playlist")
                    addOption("--user-agent", USER_AGENT)
                    addOption("--extractor-args", "youtube:player_client=android,web")
                }

                val videoInfo = try {
                    YoutubeDL.getInstance().getInfo(request)
                } catch (e: Throwable) {
                    Log.w("MediaHelper", "YoutubeDL first attempt failed", e)
                    val fallbackRequest = YoutubeDLRequest(cleanUrl).apply {
                        addOption("-f", formatSelector)
                        addOption("--no-playlist")
                        addOption("--user-agent", USER_AGENT)
                        addOption("--extractor-args", "youtube:player_client=ios,web")
                    }
                    YoutubeDL.getInstance().getInfo(fallbackRequest)
                }

                var streamUrl = videoInfo.url
                if (streamUrl.isNullOrEmpty()) {
                    streamUrl = if (isAudio) {
                        videoInfo.formats?.lastOrNull { !it.url.isNullOrEmpty() && it.acodec != "none" && it.vcodec == "none" }?.url
                            ?: videoInfo.formats?.lastOrNull { !it.url.isNullOrEmpty() }?.url
                    } else {
                        videoInfo.formats?.lastOrNull { !it.url.isNullOrEmpty() && it.vcodec != "none" && it.acodec != "none" }?.url
                            ?: videoInfo.formats?.lastOrNull { !it.url.isNullOrEmpty() }?.url
                    }
                }

                if (!streamUrl.isNullOrEmpty()) {
                    return@withContext Result.success(
                        ExtractedMedia(
                            title = videoInfo.title ?: "Přehrávané video",
                            streamUrl = streamUrl,
                            thumbnailUrl = videoInfo.thumbnail,
                            subtitles = subtitlesList
                        )
                    )
                }
            }
        } catch (e: Throwable) {
            Log.w("MediaHelper", "YoutubeDL extraction failed, falling back to NewPipeExtractor", e)
        }

        // 2. Fallback to NewPipeExtractor
        try {
            initNewPipe()
            val service = ServiceList.YouTube
            val extractor = service.getStreamExtractor(cleanUrl) as StreamExtractor
            extractor.fetchPage()

            val streamUrl = if (isAudio) {
                extractor.audioStreams?.firstOrNull()?.url
                    ?: extractor.videoStreams?.firstOrNull()?.url
            } else {
                extractor.videoStreams?.firstOrNull()?.url
                    ?: extractor.audioStreams?.firstOrNull()?.url
                    ?: extractor.videoOnlyStreams?.firstOrNull()?.url
            }

            if (!streamUrl.isNullOrEmpty()) {
                return@withContext Result.success(
                    ExtractedMedia(
                        title = extractor.name,
                        streamUrl = streamUrl,
                        thumbnailUrl = extractor.thumbnails.firstOrNull()?.url,
                        subtitles = subtitlesList
                    )
                )
            }
        } catch (e: Throwable) {
            Log.e("MediaHelper", "NewPipeExtractor failed", e)
            return@withContext Result.failure(e)
        }

        Result.failure(Exception("Nenalezen přímý odkaz na stream."))
    }

    suspend fun searchYouTube(query: String): Result<List<SearchResultItem>> = withContext(Dispatchers.IO) {
        try {
            initNewPipe()
            val service = ServiceList.YouTube
            val searchExtractor = service.getSearchExtractor(query.trim())
            searchExtractor.fetchPage()

            val items = searchExtractor.initialPage.items
                .filterIsInstance<StreamInfoItem>()
                .map { item ->
                    val durationFormatted = if (item.duration > 0) {
                        val minutes = item.duration / 60
                        val seconds = item.duration % 60
                        "%d:%02d".format(minutes, seconds)
                    } else ""

                    SearchResultItem(
                        title = item.name ?: "Neznámý název",
                        url = item.url ?: "",
                        uploader = item.uploaderName ?: "",
                        duration = durationFormatted,
                        thumbnailUrl = item.thumbnails.firstOrNull()?.url
                    )
                }

            Result.success(items)
        } catch (e: Throwable) {
            Log.e("MediaHelper", "Search error", e)
            Result.failure(e)
        }
    }

    suspend fun downloadMedia(
        context: Context,
        url: String,
        qualitySpec: String = "video_720",
        onProgress: (Float, Long) -> Unit
    ): Result<String> = withContext(Dispatchers.IO) {
        val cleanUrl = url.trim()

        // 1. Try YoutubeDL download
        try {
            if (!isInitialized) {
                try {
                    YoutubeDL.getInstance().init(context.applicationContext)
                    FFmpeg.getInstance().init(context.applicationContext)
                    isInitialized = true
                } catch (e: Throwable) {
                    Log.e("MediaHelper", "YoutubeDL init error", e)
                }
            }

            if (isInitialized) {
                val downloadsDir = Environment.getExternalStoragePublicDirectory(Environment.DIRECTORY_DOWNLOADS)
                if (!downloadsDir.exists()) {
                    downloadsDir.mkdirs()
                }

                val request = YoutubeDLRequest(cleanUrl).apply {
                    addOption("-o", "${downloadsDir.absolutePath}/%(title)s.%(ext)s")
                    when (qualitySpec) {
                        "video_1080" -> {
                            addOption("-f", "bestvideo[height<=1080]+bestaudio/best[height<=1080]/18/22/best")
                        }
                        "video_720" -> {
                            addOption("-f", "bestvideo[height<=720]+bestaudio/best[height<=720]/18/22/best")
                        }
                        "video_480" -> {
                            addOption("-f", "bestvideo[height<=480]+bestaudio/best[height<=480]/18/22/best")
                        }
                        "audio_320" -> {
                            addOption("-f", "bestaudio/best")
                            addOption("-x")
                            addOption("--audio-format", "mp3")
                            addOption("--audio-quality", "0")
                        }
                        "audio_128" -> {
                            addOption("-f", "bestaudio/best")
                            addOption("-x")
                            addOption("--audio-format", "mp3")
                            addOption("--audio-quality", "5")
                        }
                        else -> {
                            addOption("-f", "best[vcodec!=none][acodec!=none]/18/22/b/best")
                        }
                    }
                    addOption("--no-playlist")
                    addOption("--user-agent", USER_AGENT)
                    addOption("--extractor-args", "youtube:player_client=android,web")
                }

                YoutubeDL.getInstance().execute(request) { progress, etaInSeconds, _ ->
                    onProgress(progress, etaInSeconds)
                }

                return@withContext Result.success(downloadsDir.absolutePath)
            }
        } catch (e: Throwable) {
            Log.w("MediaHelper", "YoutubeDL download failed, trying DownloadManager fallback", e)
        }

        // 2. Fallback to System DownloadManager via extracted stream URL
        try {
            val extracted = extractMedia(context, cleanUrl, preferredResolution = qualitySpec).getOrThrow()
            val downloadsDir = Environment.getExternalStoragePublicDirectory(Environment.DIRECTORY_DOWNLOADS)
            val isAudio = qualitySpec.startsWith("audio")
            val extension = if (isAudio) "m4a" else "mp4"
            val fileName = "${extracted.title.replace(Regex("[^a-zA-Z0-9._-]"), "_")}.$extension"

            val request = DownloadManager.Request(extracted.streamUrl.toUri())
                .setTitle(extracted.title)
                .setDescription(if (isAudio) "Stahování zvuku..." else "Stahování videa...")
                .setNotificationVisibility(DownloadManager.Request.VISIBILITY_VISIBLE_NOTIFY_COMPLETED)
                .setDestinationInExternalPublicDir(Environment.DIRECTORY_DOWNLOADS, fileName)
                .setAllowedOverMetered(true)
                .setAllowedOverRoaming(true)

            val downloadManager = context.getSystemService(Context.DOWNLOAD_SERVICE) as DownloadManager
            downloadManager.enqueue(request)

            Result.success(downloadsDir.absolutePath)
        } catch (e: Throwable) {
            Log.e("MediaHelper", "DownloadManager fallback failed", e)
            Result.failure(e)
        }
    }
}

private class SimpleDownloader : Downloader() {
    override fun execute(request: Request): Response {
        val url = URL(request.url())
        val conn = url.openConnection() as HttpURLConnection
        conn.requestMethod = request.httpMethod()

        // Set realistic User-Agent and Accept-Language
        conn.setRequestProperty("User-Agent", "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/121.0.0.0 Safari/537.36")
        conn.setRequestProperty("Accept-Language", "en-US,en;q=0.9")

        request.headers().forEach { (key, values) ->
            if (!key.equals("User-Agent", ignoreCase = true)) {
                values.forEach { value -> conn.addRequestProperty(key, value) }
            }
        }

        // Send POST body data if present
        val requestBody = request.dataToSend()
        if (requestBody != null && requestBody.isNotEmpty()) {
            conn.doOutput = true
            conn.outputStream.use { os ->
                os.write(requestBody)
            }
        }

        conn.connect()
        val responseCode = conn.responseCode
        val responseMessage = conn.responseMessage
        val headers = conn.headerFields.filterKeys { it != null }
        val stream: InputStream? = if (responseCode in 200..299) conn.inputStream else conn.errorStream
        val responseBody = stream?.bufferedReader()?.use { it.readText() } ?: ""
        return Response(responseCode, responseMessage, headers, responseBody, request.url())
    }
}
